export function compactRepairText(value=''){
 return wording.reduce((text,[original,brief])=>text.replaceAll(original,brief),value)
}

export function compactRepairRecordHint(step){
 let text=compactRepairText(step.recordHint||'')
 for(const substep of step.substeps||[])text=text.replaceAll(`${substep.label}：`,'')
 return [...new Set(text.split('\n').map(line=>line.trim()).filter(Boolean))].join(' ')
}
