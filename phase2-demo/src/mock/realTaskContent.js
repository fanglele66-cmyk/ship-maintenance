export function assigneeStageMarkdown(type,stage,conclusion){
 const brief=assigneeBriefs[type]
 if(!brief)return ''
 if(stage.kind==='intro')return `### 任务目标\n\n${brief.objective}\n\n### 接单后工作\n\n${brief.actions.map(text=>'- '+text).join('\n')}\n\n### 提交成果\n\n${brief.deliverables}\n\n### 事件依据\n\n${conclusion}`
 const focus=stage.kind==='check'?brief.check:stage.kind==='event'?'依据已核实的低压记录，接续减压阀与供气通路检查；分别提交定位结果和本次建议处置范围。':stage.kind==='observe'?brief.observation:stage.kind==='closed'?'核对本轮措施、验收、观察及仍需跟进的项目，保留全部原始记录。':'按已确认检查发现执行获批范围，完成部位复装、功能测试并提交验收。'
 return `### 执行要求\n\n${focus}\n\n${stage.tasks?.length?'### 本阶段工作\n\n'+stage.tasks.map(task=>'- **'+task.label+'**：'+task.guide).join('\n'):''}\n\n### 反馈要求\n\n${brief.deliverables}`
}
