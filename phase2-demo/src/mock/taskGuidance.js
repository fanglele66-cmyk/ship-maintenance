export function guidedTask(task) {
  if(task.checks?.length)return task
  const found=guidance[task.label]||guidance[task.label?.replace('评估一缸专项','评估四缸专项')]
  if(found)return {...task,...found}
  return task.checks?.length?task:{...task,checks:['对照当前部位、测点与原始记录，确认本轮检查范围和作业条件。','按适用工卡核对实际状态，保留读数、检查位置与时间；受限项目单独记录。','对比现场发现与原异常，说明已支持或尚未排除的原因，再选择本项检查结果。'],recordHint:task.recordHint||'记录检查时间、实际发现、依据与未完成项目。'}
}

export function checkPreparation(item,stage) {
  if(stage.preparation?.length)return stage.preparation
  const maintenance=maintenanceTaskPreparation(item)
  if(maintenance)return maintenance
  if(item.realType==='warning'&&stage.id==='event')return ['备齐低压窗口 0302、0303 与就地仪表记录，统一测点、单位及采样时刻。','准备供气切换、阀组使用和同期用气记录；先核对低压事实及工况，再确定原因排查方向。']
  if(item.realType==='alarm')return ['备齐报警前后喷射指令、流量活塞反馈、六缸排温及燃油压力记录。','核对二缸 ICU 和供给通路图册，明确本轮可检查范围；拆检前落实停机、防起动及隔离卸压。','准备记录表、拍照及适配检测工具；按控制/液压和燃油供给两个方向分别提交结果。']
  if(item.realType==='warning')return ['准备空气系统图、阀组编号及双路/分段压力记录。','确认可用供气路径和用气协调安排，需拆检的段落先获准隔离卸压。','备齐查漏、压力核对工具及工卡，分别记录减压环节与供给通路结果。']
  return ['备齐月度六缸数据、负荷/燃油及历史调整记录，标明本轮核对月份与部位。','核对探头通道、校验记录和适配检测工具；现场检查按已批准窗口与范围开展。','分别记录资料覆盖、实际发现及受限项，提出下一步核实或作业所需条件。']
}
