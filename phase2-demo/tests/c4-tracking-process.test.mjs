import test from 'node:test'
import assert from 'node:assert/strict'
import {createServer} from 'vite'
import {createPinia,setActivePinia} from 'pinia'

test('C4 resumes at a second captain decision with retained first-round context',async t=>{
 const server=await createServer({optimizeDeps:{noDiscovery:true,include:[]},server:{middlewareMode:true,hmr:false,ws:false},appType:'custom'})
 try{
  const {usePhase2DemoStore}=await server.ssrLoadModule('/src/stores/phase2DemoStore.js')
  const {storyTimeline,storyRevision}=await server.ssrLoadModule('/src/mock/storyRecords.js')
  const {trackingProcessReference}=await server.ssrLoadModule('/src/mock/trackingProcessReferences.js')
  const {eventDirectoryRows}=await server.ssrLoadModule('/src/mock/eventDirectory.js')
  const {eventProcessRecords}=await server.ssrLoadModule('/src/mock/eventProcessRecords.js')
  const {issueConversationMessages,mergeIssueConversation,issueReply}=await server.ssrLoadModule('/src/message-flows/issueSources.js')
  const {realCaseRecords}=await server.ssrLoadModule('/src/mock/realCaseAdapter.js')
  const id='real-health-c4-baseline',child='real-maintenance-c4-baseline',track=id+'-track'
  const fresh=()=>{setActivePinia(createPinia());return usePhase2DemoStore()}
  const reference=trackingProcessReference(id),raw=JSON.stringify(realCaseRecords)
  const priorIds=reference.records.map(record=>record.id)
  const preserved=store=>{
   const timeline=storyTimeline(store,id)
   assert.deepEqual(timeline.slice(1,5).map(record=>record.id),priorIds)
   assert.equal(new Set(timeline.map(record=>record.id)).size,timeline.length)
   assert.equal(JSON.stringify(realCaseRecords),raw)
  }
  await t.test('source, first assignment, feedback, analysis and handoff precede the current decision',()=>{
   const store=fresh(),timeline=storyTimeline(store,id)
   assert.deepEqual(timeline.map(record=>record.kind),['source','assignment','feedback','analysis','decision'])
   assert.equal(timeline[0].isSimulation,false)
   assert.ok(timeline.slice(1).every(record=>record.isSimulation&&record.dataOrigin==='prototype-reference'))
   assert.deepEqual(timeline.map(record=>record.at),timeline.map(record=>record.at).sort())
   assert.match(timeline[2].text,/独立测温校验原始记录仍待补充/)
   assert.equal(store.trackingDispositions[id].status,'review')
   assert.equal(store.eventStatus[id],'awaiting-decision')
   assert.equal(store.healthUpdates[track].taskComplete,true)
   assert.equal(store.canDecideTracking(id),true)
   assert.equal(store.workflowRounds[child],1)
   assert.equal(store.visibleTodos.length,0)
   assert.equal(store.storyJournal.length,0)
   assert.deepEqual(storyTimeline(store,track),timeline)
   assert.deepEqual(storyTimeline(store,child,{taskOnly:true}),[])
   assert.equal(storyTimeline(store,'real-tracking-exhaust-baseline').length,1)
   const row=eventDirectoryRows(store).find(row=>row.id===id)
   assert.equal(row.processingState,'待轮机长确认')
   assert.match(row.progressNote,/首轮核实已回交/)
   preserved(store)
  })
  await t.test('all event surfaces share the same history, and repeat visits do not duplicate it',()=>{
   const store=fresh()
   for(let index=0;index<3;index++)store.openRealCase(id)
   const records=eventProcessRecords(store,id).records
   assert.deepEqual(records.slice(-4).map(record=>record.id),priorIds)
   const messages=issueConversationMessages(id,store),existing=[]
   mergeIssueConversation(existing,messages);mergeIssueConversation(existing,issueConversationMessages(id,store))
   assert.equal(existing.length,messages.length)
   assert.ok(priorIds.every(id=>existing.some(message=>message.eventRecordId===id)))
   assert.equal(storyRevision(store,id),priorIds.at(-1))
   assert.match(existing.at(-1).markdown,/首轮核实已回交/)
   assert.match(issueReply(id,'下一步如何安排？',store).markdown,/工况、调整及独立校验缺项/)
   preserved(store)
  })
  await t.test('a new explanation closes only after a captain action and preserves the first round',()=>{
   const store=fresh()
   assert.equal(store.decideTracking(id,'explained',{reason:'补充的可比工况及校验依据已人工确认，按本次范围解释变化'}).ok,true)
   assert.equal(store.trackingDispositions[id].status,'closed')
   assert.equal(storyTimeline(store,id).at(-1).kind,'closure')
   preserved(store)
   assert.equal(store.resetRealScenario(id),true)
   assert.equal(store.trackingDispositions[id].status,'review')
   assert.equal(storyTimeline(store,id).length,5)
   store.resetDemo()
   assert.equal(store.trackingDispositions[id].status,'review')
   assert.equal(store.visibleTodos.length,0)
   preserved(store)
  })
  await t.test('maintenance arrangement keeps prior history and creates only its explicitly approved task',()=>{
   const store=fresh()
   assert.equal(store.decideTracking(id,'maintenance',{reason:'独立校验与调整依据仍缺，安排专项核验',scope:'核验测温链路，结合可比资料确定燃烧检查范围'}).ok,true)
   assert.equal(store.visibleTodos.length,0)
   assert.equal(store.confirmTrackingMaintenance(id,{owner:'李建国（大管轮）',due:'下一靠港窗口',scope:'批准范围内测温核验',conditions:'仪器与许可落实，停机隔离后实施'}).ok,true)
   assert.deepEqual(store.visibleTodos.map(item=>item.id),[child])
   assert.equal(store.executionRecords[child],undefined)
   assert.ok(storyTimeline(store,id).at(-1).text.includes('下一靠港窗口'))
   assert.ok(storyTimeline(store,child,{taskOnly:true}).every(record=>!priorIds.includes(record.id)))
   preserved(store)
  })
  await t.test('new observation feedback returns to review without erasing the previous handoff',()=>{
   const store=fresh(),task='real-observation-c4-baseline'
   const deadline=new Date(Date.now()+86400000).toISOString().slice(0,16)
   assert.equal(store.decideTracking(id,'observe',{deadline,owner:'李建国（大管轮）',metrics:'同刻六缸与负荷、独立测温记录',criteria:'补足可比工况及校验资料后重新评估'}).ok,true)
   assert.deepEqual(store.activeTaskPortfolio.map(item=>item.id),[task])
   assert.equal(store.submitTrackingObservation(id,{observedAt:'2026-10-26T10:00',findings:'新增记录已提交；仍缺独立校验，保持未确认'}).ok,true)
   assert.equal(store.trackingDispositions[id].status,'review')
   assert.match(issueReply(id,'当前进展',store).markdown,/新增记录已提交/)
   assert.equal(store.activeTaskPortfolio.length,0)
   preserved(store)
  })
  await t.test('the observation task shows retained first-round findings alongside later observation submissions',async()=>{
   const store=fresh(),task='real-observation-c4-baseline'
   const plan={deadline:new Date(Date.now()+86400000).toISOString().slice(0,16),owner:'李建国（大管轮）',metrics:'六缸同刻记录与测温依据',criteria:'补足独立测温后重新判断'}
   assert.equal(store.decideTracking(id,'observe',plan).ok,true)
   const {default:Component}=await server.ssrLoadModule('/src/components/TrackingObservationTask.vue')
   const {createSSRApp}=await import('vue'),{renderToString}=await import('@vue/server-renderer')
   const {getActivePinia}=await import('pinia'),{routerKey}=await import('vue-router')
   const render=()=>{const app=createSSRApp(Component,{taskId:task});app.use(getActivePinia());app.provide(routerKey,{push(){}});return renderToString(app)}
   const first=await render()
   assert.match(first,/首轮核实与回交记录/)
   assert.match(first,/独立测温校验原始记录仍待补充/)
   assert.equal(store.completedTasks[id],undefined,'retained context is not a fabricated live completion')
   assert.equal(store.checkAssessments[id],undefined)
   assert.equal(store.submitTrackingObservation(id,{observedAt:'2026-08-13T10:00',findings:'首轮之后新增观察原文'}).ok,true)
   assert.equal(store.decideTracking(id,'observe',plan).ok,true)
   const next=await render()
   assert.match(next,/首轮之后新增观察原文/)
   assert.equal((next.match(/首轮核实与回交记录/g)||[]).length,1)
   preserved(store)
  })
  await t.test('resetting a tracking parent clears its executable children while child-only reset preserves the parent history',()=>{
   const store=fresh(),observation='real-observation-c4-baseline'
   const plan={deadline:new Date(Date.now()+86400000).toISOString().slice(0,16),owner:'李建国（大管轮）',metrics:'六缸同刻记录',criteria:'补足测温依据'}
   assert.equal(store.decideTracking(id,'observe',plan).ok,true)
   assert.equal(store.submitTrackingObservation(id,{observedAt:'2026-08-13T10:00',findings:'待重置的新增观察'}).ok,true)
   assert.equal(store.decideTracking(id,'maintenance',{reason:'补充校验仍待实施',scope:'四缸测温链路核验'}).ok,true)
   assert.equal(store.confirmTrackingMaintenance(id,{owner:'李建国（大管轮）',due:'靠港窗口',scope:'批准的四缸测温核验',conditions:'准备校验仪并隔离'}).ok,true)
   const disposition=JSON.stringify(store.trackingDispositions[id])
   assert.equal(store.resetRealScenario(child),true)
   assert.equal(JSON.stringify(store.trackingDispositions[id]),disposition,'child reset cannot reset the parent decision')
   preserved(store)
   assert.equal(store.createTodo(child),true)
   store.selectTodo(child)
   assert.equal(store.resetRealScenario(id),true)
   for(const task of [child,observation]){
    assert.equal(store.todoCreated[task],false)
    assert.equal(store.logs[task].length,0)
    assert.equal(store.assignmentRecords[task],undefined)
    assert.equal(store.completedTasks[task],undefined)
    assert.equal(store.trackingObservationDrafts[task],undefined)
    assert.equal(store.unlockedRecommendations[task],undefined)
    assert.equal(store.storyJournal.some(entry=>entry.taskId===task),false)
   }
   assert.equal(store.selectedTodoId,null)
   assert.equal(store.visibleTodos.length,0)
   assert.equal(store.trackingDispositions[id].status,'review')
   assert.equal(store.trackingDispositions[id].plan,undefined)
   assert.equal(storyTimeline(store,id).length,5)
   preserved(store)
  })
  await t.test('legacy direct maintenance creation replaces only the untouched initial review state',()=>{
   const legacy=fresh()
   assert.equal(legacy.trackingDispositions[id].priorProcessId,reference.id)
   assert.equal(legacy.createTodo(child),true)
   assert.equal(legacy.trackingDispositions[id],undefined)
   assert.ok(eventDirectoryRows(legacy).find(row=>row.id===id).taskIds.includes(child))
   preserved(legacy)
   const approved=fresh()
   assert.equal(approved.decideTracking(id,'maintenance',{reason:'明确批准前的依据',scope:'四缸测温核验'}).ok,true)
   const recommendation=JSON.stringify(approved.trackingDispositions[id])
   assert.equal(approved.createTodo(child),true)
   assert.equal(JSON.stringify(approved.trackingDispositions[id]),recommendation,'explicit maintenance recommendation remains authoritative')
   preserved(approved)
  })
  await t.test('legacy assignment and ignored advice replace the initial review only after a valid new action',()=>{
   const assigned=fresh()
   assert.equal(assigned.assignTask(child,assigned.defaultAssignment(child)),false)
   assert.equal(assigned.trackingDispositions[id].priorProcessId,reference.id,'failed assignment cannot remove the starting decision')
   assigned.todoCreated[child]=true
   assert.equal(assigned.assignTask(child,assigned.defaultAssignment(child)),true)
   assert.equal(assigned.trackingDispositions[id],undefined)
   preserved(assigned)
   const ignored=fresh()
   assert.equal(ignored.ignoreSuggestion(child,''),false)
   assert.equal(ignored.trackingDispositions[id].priorProcessId,reference.id)
   assert.equal(ignored.ignoreSuggestion(child,'本次暂不安排专项检查，保留缺项继续跟踪'),true)
   assert.equal(ignored.trackingDispositions[id],undefined)
   assert.match(ignored.ignoredSuggestions[child].reason,/暂不安排/)
   preserved(ignored)
   for(const action of ['assign','ignore']){
    const explicit=fresh()
    assert.equal(explicit.decideTracking(id,'maintenance',{reason:'明确检查依据',scope:'四缸测温核验'}).ok,true)
    const before=JSON.stringify(explicit.trackingDispositions[id])
    if(action==='assign'){explicit.todoCreated[child]=true;assert.equal(explicit.assignTask(child,explicit.defaultAssignment(child)),true)}
    else assert.equal(explicit.ignoreSuggestion(child,'保留已确认的维保方向，当前不派发'),true)
    assert.equal(JSON.stringify(explicit.trackingDispositions[id]),before,'explicit captain choice is not a default snapshot')
    preserved(explicit)
   }
  })
 }finally{await server.close()}
})
