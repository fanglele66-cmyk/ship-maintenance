import test from 'node:test'
import assert from 'node:assert/strict'
import {automaticObservation,automaticObservationTime} from '../src/mock/automaticObservation.js'

const hour=3600000,minute=60000,start=Date.parse('2026-10-27T00:00:00+08:00')
const point=(minutes,value=minutes)=>({timestamp:start+minutes*minute,value})
const sensor=(trendData,overrides={})=>({channelId:'DC0009',name:'二缸排温',unit:'°C',sourceKind:'prototype-stream',trendData,...overrides})

test('two-hour windows are execution-aligned and retain boundary values without shifting, interpolation or future samples',()=>{
 const points=Array.from({length:301},(_,index)=>point(index))
 points.push(point(301,99999))
 const sensors=[sensor(points),sensor(points.map(p=>({time:new Date(p.timestamp).toISOString(),value:p.value+10})),{channelId:'DC0008',name:'一缸排温'})]
 const original=JSON.stringify(sensors)
 const result=automaticObservation({sensors,executedAt:'2026-10-27 00:00:00',now:start+5*hour})
 assert.equal(result.error,null)
 assert.equal(result.records.length,2)
 assert.deepEqual(result.records.map(r=>r.values),[[120,130],[240,250]])
 assert.deepEqual(result.records.map(r=>r.sampleCount),[240,240],'start boundary is exclusive and each numeric row is counted once')
 assert.ok(result.records.every(r=>r.covered&&r.status==='observed'&&r.auto&&r.complete))
 assert.equal(result.records[0].day,2/24)
 assert.equal(result.records[0].windowEnd,new Date(start+2*hour).toISOString())
 assert.equal(result.records[0].recordedAt,new Date(start+5*hour).toISOString(),'receipt time is actual calculation time')
 assert.deepEqual(result.pending.values,[300,310])
 assert.equal(result.pending.status,'pending')
 assert.equal(result.pending.covered,false)
 assert.equal(result.pending.complete,false)
 assert.equal(result.nextUpdateAt,new Date(start+6*hour).toISOString())
 assert.equal(JSON.stringify(sensors),original,'input samples remain untouched')
 assert.deepEqual(automaticObservation({sensors,executedAt:start,now:start+5*hour}).records.map(r=>r.id),result.records.map(r=>r.id))
})

test('empty windows and absent channels remain missing; earlier values are never carried forward',()=>{
 const result=automaticObservation({sensors:[sensor([point(-1,600),point(0,500),point(1,400),point(121,null),point(125,NaN),point(241,300)]),sensor([],{channelId:'DC0008',name:'一缸排温'})],executedAt:start,now:start+6*hour})
 assert.equal(result.records.length,3)
 assert.deepEqual(result.records.map(r=>r.values),[[400,null],[null,null],[300,null]])
 assert.ok(result.records.every(r=>r.status==='incomplete'&&!r.covered))
 assert.equal(result.records[1].channels[0].missingCount,2)
 assert.equal(result.records[1].sampleCount,0)
 assert.match(result.records[1].note,/缺测通道：二缸排温、一缸排温/)
 assert.equal(result.pending,null)
})

test('coverage checks leading, interior and trailing gaps, and null samples independently',()=>{
 const full=Array.from({length:120},(_,index)=>point(index+1))
 const run=points=>automaticObservation({sensors:[sensor(points)],executedAt:start,now:start+2*hour}).records[0]
 assert.equal(run(full).covered,true)
 assert.equal(run(full.slice(3)).covered,false,'missing leading interval is visible')
 assert.equal(run(full.slice(0,-3)).covered,false,'missing trailing interval is visible')
 assert.equal(run(full.filter(p=>p.timestamp<start+60*minute||p.timestamp>start+64*minute)).covered,false)
 assert.equal(run(full.map((p,i)=>i===50?{...p,value:null}:p)).covered,false,'explicit null is not erased by adjacent samples')
 assert.equal(run(full).channels[0].min,1)
 assert.equal(run(full).channels[0].max,120)
 assert.equal(run(full).channels[0].mean,60.5)
})

test('source identity is retained and no coverage result becomes a recovery or normal diagnosis',()=>{
 const full=Array.from({length:120},(_,index)=>point(index+1))
 const prototype=automaticObservation({sensors:[sensor(full)],executedAt:start,now:start+2*hour})
 assert.equal(prototype.sourceKind,'prototype-stream')
 assert.equal(prototype.records[0].isSimulation,true)
 assert.match(prototype.records[0].note,/原型传感器流，非实船实时数据/)
 assert.match(prototype.records[0].note,/不等同于工况可比、异常消除或修复成功/)
 assert.notEqual(prototype.records[0].status,'normal')
 const historical=automaticObservation({sensors:[sensor(full,{sourceKind:'historical-sensor-samples'})],executedAt:start,now:start+2*hour})
 assert.equal(historical.sourceKind,'historical-sensor-samples')
 assert.match(historical.source,/保留原时戳/)
 const mixed=automaticObservation({sensors:[sensor(full),sensor([],{channelId:'other',sourceKind:'unknown'})],executedAt:start,now:start+2*hour})
 assert.equal(mixed.sourceKind,'mixed')
 assert.deepEqual(mixed.records[0].channels.map(c=>c.sourceKind),['prototype-stream','unknown'])
})

test('only the latest bounded windows are computed and truncation is explicit',()=>{
 const result=automaticObservation({sensors:[sensor([])],executedAt:start,now:start+100*hour})
 assert.equal(result.records.length,36)
 assert.equal(result.range.omittedCompletedWindows,14)
 assert.equal(result.range.start,new Date(start+28*hour).toISOString())
 assert.equal(result.truncated,true)
 assert.match(result.truncationNote,/14 个窗口/)
 assert.ok(result.records.every(r=>r.status==='incomplete'))
 const partial=automaticObservation({sensors:[],executedAt:start,now:start+101*hour})
 assert.equal(partial.records.length,35)
 assert.equal(partial.range.omittedCompletedWindows,15)
 assert.equal(partial.pending.windowStart,new Date(start+100*hour).toISOString())
})

test('invalid execution times, unknown sources and partial windows cannot fabricate completed observations',()=>{
 assert.equal(automaticObservationTime('2026-10-27 00:00:00'),start)
 assert.equal(automaticObservationTime('2026-10-26T16:00:00Z'),start)
 assert.ok(Number.isNaN(automaticObservationTime('00:00:00')))
 assert.ok(automaticObservation({sensors:[],executedAt:start+hour,now:start}).error)
 assert.ok(automaticObservation({sensors:[],executedAt:'bad',now:start}).error)
 assert.ok(automaticObservation({sensors:[],executedAt:start,now:start,intervalMs:0}).error)
 const partial=automaticObservation({sensors:[sensor([point(30,123)])],executedAt:start,now:start+hour})
 assert.equal(partial.records.length,0)
 assert.deepEqual(partial.pending.values,[123])
 assert.equal(partial.pending.status,'pending')
 const empty=automaticObservation({sensors:[],executedAt:start,now:start+2*hour})
 assert.equal(empty.records[0].sampleCount,0)
 assert.equal(empty.records[0].covered,false)
 assert.equal(empty.records[0].sourceKind,'unknown')
 assert.match(empty.records[0].note,/尚未接入本轮监测通道/)
})
