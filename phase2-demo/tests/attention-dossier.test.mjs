import test from 'node:test'
import assert from 'node:assert/strict'
import { createServer } from 'vite'
import { createPinia, setActivePinia } from 'pinia'

test('attention dossier reuses evidence, preserves history and handles all phases',async()=>{
  const server=await createServer({optimizeDeps:{noDiscovery:true,include:[]},server:{middlewareMode:true,hmr:false,ws:false},appType:'custom'})
  try {
    const {usePhase2DemoStore}=await server.ssrLoadModule('/src/stores/phase2DemoStore.js')
    const {attentionDossier}=await server.ssrLoadModule('/src/mock/attentionDossier.js')
    setActivePinia(createPinia())
    const store=usePhase2DemoStore();store.createTodo('fault')
    const initial=attentionDossier(store,'drift')
    assert.deepEqual(initial.charts[0].values,[425,428,430,432])
    assert.equal(initial.charts[0].unit,'°C','prototype fixture has explicit units')
    const before=JSON.stringify(initial.records)
    const originalAnalysisTime=initial.analysisAt
    store.askDossierQuestion('drift','为何关注？','基于已有档案的演示回答')
    assert.equal(attentionDossier(store,'drift').records.length,initial.records.length,'ordinary questions are not journal evidence')
    assert.equal(store.registerDossierNote('drift','现场未见异响，建议保留观察'),true)
    const noted=attentionDossier(store,'drift')
    assert.equal(noted.records.at(-1).type,'note')
    assert.equal(noted.records.at(-1).text,'现场未见异响，建议保留观察')
    assert.equal(noted.analysisAt,originalAnalysisTime,'a note does not advance analysis time')
    assert.equal(noted.action.required,true,'a note cannot satisfy verification')
    assert.equal(store.todoCreated.drift,false)
    assert.match(noted.comparisonRows.find(row=>row.name==='较长期历史').result,/近30天/)
    assert.equal(noted.sources.some(source=>source.event),false)
    store.submitAttentionFeedback('drift',{reading:432,conditions:'450rpm，稳定负荷，08:00',phenomenon:'未见明显异响',confirmed:true})
    const after=attentionDossier(store,'drift')
    assert.equal(JSON.stringify(after.records.slice(0,initial.records.length)),before)
    assert.equal(after.feedback.reading,432)
    assert.equal(after.action.phase,'系统跟踪中')
    assert.equal(store.todoCreated.drift,false)
    store.createTodo('drift')
    assert.equal(attentionDossier(store,'drift').records.some(record=>record.label==='现场核实 · 已提交'),true,'creating a linked event must not hide earlier feedback')
    assert.equal(attentionDossier(store,'cyl2-ended').action.phase,'已结束')
    assert.equal(attentionDossier(store,'stable'),null,'ordinary pressure data does not have a dossier')
    assert.equal(attentionDossier(store,'vibration-trend'),null)
    assert.equal(attentionDossier(store,'cyl4-watch').action.phase,'系统跟踪中')
    store.progress.fault=store.observationIndex('fault')
    store.observationRecords.fault.push({label:'首测',status:'normal',day:0,values:[79.1,86.5]},{label:'缺失记录',status:'incomplete',day:1})
    const observed=attentionDossier(store,'fault')
    assert.equal(observed.action.phase,'处理后观察')
    assert.deepEqual(observed.charts[0].values,[92.4,79.1,null],'missing samples stay missing')
    assert.equal(observed.records.at(-1).label,'缺失记录')
    assert.equal(attentionDossier(store,'missing'),null)
    store.progress.maintenance=store.observationIndex('maintenance')
    store.observationRecords.maintenance.push({label:'首测',status:'normal',day:0,values:[2.2,64]},{label:'第1日',status:'normal',day:1,values:[2.2,64]})
    assert.equal(attentionDossier(store,'maintenance').records.filter(record=>record.label==='第1日').length,1,'observation records have one canonical source')
    store.resetDemo();store.createTodo('fault')
    assert.equal(Object.keys(store.dossierNotes).length,0)
  } finally {await server.close()}
})
